#!/usr/bin/env node
/* Generates shared/maze-levels.js: 20 big, looped (multi-route) mazes for Guide the Robot.
 * Run:  node tools/gen_mazes.js
 * Mazes are generated ONCE here and stored; nothing random happens at play time. */
'use strict';
const fs = require('fs');
const path = require('path');
const M = require('../shared/maze-lib.js');

const NAMES = [
  'First Steps', 'Garden Gate', 'Two Ways Home', 'Copper Lane', 'The Long Hedge',
  'Crossroads', 'Echo Court', 'Hidden Loop', 'Salt Flats', 'The Weave',
  'Lantern Row', 'Split Decision', 'Old Quarter', 'Winding Stair', 'Mirror Maze',
  'The Labyrinth', 'Iron Gardens', 'Deep Tangle', 'Grand Circuit', 'The Enigma'
];

// cells per side (rows x cols), braid share (loops), minimum number of different routes, target length of the best program
const LEVELS = [];
for (let i = 1; i <= 20; i++) {
  const side = [5, 5, 6, 6, 7, 7, 8, 8, 8, 9, 9, 9, 10, 10, 10, 11, 11, 12, 12, 12][i - 1];
  LEVELS.push({
    rows: side,
    cols: i % 2 === 0 ? side + 1 : side,
    braid: 0.10 + (i - 1) * 0.011,
    minRoutes: i <= 3 ? 2 : i <= 8 ? 4 : i <= 14 ? 8 : 16,
    target: Math.round(24 + (i - 1) * 3.6)
  });
}

const out = [];
const used = new Set();
LEVELS.forEach((spec, k) => {
  let best = null;
  for (let seed = 1; seed <= 1500; seed++) {
    const g = M.generate(spec.rows, spec.cols, seed * 7919 + k * 104729, spec.braid);
    const maze = M.parse(g.map, g.dir);
    const sol = M.solve(maze);
    if (!sol) continue;
    const score = Math.abs(sol.length - spec.target);
    if (best && score >= best.score) continue;
    const key = g.map.join('|');
    if (used.has(key)) continue;
    const routes = M.countSimplePaths(maze, spec.minRoutes, 200000);
    if (routes.count < spec.minRoutes) continue;
    best = { score: score, g: g, maze: maze, sol: sol, seed: seed };
    if (score <= 1) break;
  }
  if (!best) throw new Error('No maze found for level ' + (k + 1));
  used.add(best.g.map.join('|'));
  const a = M.analyze(best.maze);
  out.push({
    id: k + 1,
    name: NAMES[k],
    dir: best.g.dir,
    map: best.g.map,
    stats: {
      size: a.rows + 'x' + a.cols,
      fewestInstructions: a.fewestInstructions,
      routes: a.routes,
      routesCapped: a.routesCapped,
      loops: a.loops,
      deadEnds: a.deadEnds
    }
  });
  console.log('L' + String(k + 1).padStart(2), a.rows + 'x' + a.cols, 'instr', a.fewestInstructions, 'routes', a.routes + (a.routesCapped ? '+' : ''), 'loops', a.loops, 'deadEnds', a.deadEnds);
});

const file = path.join(__dirname, '..', 'shared', 'maze-levels.js');
fs.writeFileSync(file,
  '/* Generated by tools/gen_mazes.js - the built-in Guide the Robot mazes.\n' +
  ' * Tiles: # wall, . floor, S robot start, G goal. dir = direction the robot faces at the start.\n' +
  ' * Every maze is checked by tools/validate_mazes.js. */\n' +
  '(function (root) {\n  var levels = ' + JSON.stringify(out, null, 1) + ';\n  if (typeof module === "object" && module.exports) module.exports = levels;\n  else root.EP_MAZE_LEVELS = levels;\n}(typeof self !== "undefined" ? self : this));\n');
console.log('wrote', file);
